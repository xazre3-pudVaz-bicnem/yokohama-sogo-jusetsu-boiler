/**
 * 給湯器コラムの題材の一覧（自動投稿はここから1日1本を選ぶ。ランダムには書かせない）。
 *
 * 1題材 ＝ 1検索意図 ＝ 1主キーワード。題材ごとに、ジャンル（カテゴリ）・主キーワード・答える検索意図・
 * 書く内容・関連する固定ページと機種・使ってよい事実シートの節・優先度を決めておく。
 * ここにあるのは「事実シートで書ける」題材だけ。まだ書けない候補（事実の確認が要るもの）は backlog.ts に置く。
 *
 * 選び方（generate.ts の rankTopics）
 *   1. すでに記事がある題材（slug が同じ・主キーワードが同じ・検索意図が近い）は選ばない
 *   2. 季節の題材は、決めた月だけ。補助金の題材は、制度が受付中のときだけ
 *   3. 優先度の高い順（P0 → P1 → P2）
 *   4. 同じ優先度の中では、前の記事と違うカテゴリを先に、記事の少ないカテゴリを先に（偏りをなくす）
 *   5. それも同じなら、この配列の上から順に
 *   live（最新の公式情報を確かめる題材）は、その日に公式ページを取り直せたときだけ書く。取り直せなければ、ほかの題材にする。
 *
 * 題材を足すとき
 *   - slug は半角の英小文字とハイフン。公開後は変えない（URL になる）
 *   - keyword は、固定ページが担当している検索語（lib/blog-generator/keywords.ts）・ほかの題材・公開済みの記事と同じ語にしない
 *     （npm run blog:selftest が、重なりを知らせる）
 *   - 数値や制度に触れる題材は、先に docs/VERIFIED_FACTS.md に出典つきで事実を足し、facts にその節の名前（前方一致）を書く
 *   - angle・titleHint に数値を書いたら、その数値が facts の節にあること（selftest が確かめる）
 *   - 固定ページと同じ検索意図の題材は作らない。そのページを直す
 */
export type TopicPriority = "P0" | "P1" | "P2";

export type Topic = {
  slug: string;
  cluster: BlogClusterId;
  /** 主キーワード（この記事が代表になる検索語。記事の keywords の先頭に入る） */
  keyword: string;
  /** この記事が答える検索意図（重複の判定にも使う） */
  intent: string;
  priority: TopicPriority;
  /** タイトルの方向（そのまま使わなくてよい） */
  titleHint: string;
  /** 書く内容（見出しの候補・必ず触れる点） */
  angle: string[];
  /** 関連する固定ページ（本文から1本以上リンクする。記事の末尾にも出す）。カテゴリの親ページは自動で足す */
  pages: string[];
  /** 関連する機種（data/products の id）。挙げたら、本文から1本以上の機種のページへリンクする。機種の節は事実シートの範囲に自動で足す */
  products?: string[];
  /** 関連する地域ページ（data/areas の slug） */
  areas?: string[];
  /** 数値を使ってよい事実シートの節（前方一致）。「会社」「当社の交換工事の進め方」「設備の一般的な知識」「書かないこと」は常に渡す */
  facts: string[];
  /** 季節の題材：書いてよい月（日本時間の 1〜12） */
  months?: number[];
  /** 補助金の題材：国の給湯省エネ2026事業が受付中（lib/subsidy.ts の kyutouPhase が open）のときだけ書く */
  requiresOpenProgram?: boolean;
  /** その日に公式ページを取り直して確かめる題材（取り直せた日だけ書く） */
  live?: LiveSpec;
  /** 記事の冒頭の図（省略するとカテゴリの絵） */
  figure?: FigureKind;
  /** 本文の長さ（空白・記号を除く字数）。省略時は 1800〜3800 字（目安は 2000〜3500 字） */
  length?: { min: number; max: number };
};

